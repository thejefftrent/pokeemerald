#!/usr/bin/env python3
"""Generate the gift/static/starter encounter table from ce/encounters.json.

    python3 tools/ce/gen_encounters.py ce/encounters.json include/constants/ce_encounters.h src/data/ce_encounters.h

Writes CE_ENC_* ids (usable from scripts and C) and the gCeEncounters / gCeEncounterInfo
initializers. Files are only rewritten when their content changes.
"""
import json
import re
import sys

KINDS = ["starter", "gift", "egg", "static", "event", "roamer", "tutorial", "trade", "trade-request"]
TRADE_KINDS = {"trade", "trade-request"}
CONSTANT = re.compile(r"^[A-Z][A-Z0-9_]*$")


def kind_constant(kind: str) -> str:
    return "CE_ENC_KIND_" + kind.upper().replace("-", "_")


def load(path: str) -> list[dict]:
    with open(path, encoding="utf-8") as f:
        encounters = json.load(f)["encounters"]
    seen = set()
    for e in encounters:
        where = e.get("id", "?")
        if not CONSTANT.match(e.get("id", "")):
            sys.exit(f"{path}: bad id {where!r}")
        if e["id"] in seen:
            sys.exit(f"{path}: duplicate id {where}")
        seen.add(e["id"])
        if e.get("kind") not in KINDS:
            sys.exit(f"{path}: {where}: kind must be one of {', '.join(KINDS)}")
        for field, prefix in (("map", "MAP_"), ("species", "SPECIES_")):
            if not str(e.get(field, "")).startswith(prefix):
                sys.exit(f"{path}: {where}: {field} must be a {prefix} constant")
        if not str(e.get("item", "ITEM_NONE")).startswith("ITEM_"):
            sys.exit(f"{path}: {where}: item must be an ITEM_ constant")
        if not isinstance(e.get("level"), int) or not 0 <= e["level"] <= 100:
            sys.exit(f"{path}: {where}: level must be 0-100")
        if (e["kind"] in TRADE_KINDS) != ("trade" in e):
            sys.exit(f"{path}: {where}: trade rows (and only they) name their INGAME_TRADE_* entry")
    return encounters


def constants_header(encounters: list[dict]) -> str:
    lines = [
        "// Generated by tools/ce/gen_encounters.py from ce/encounters.json. Do not edit.",
        "#ifndef GUARD_CONSTANTS_CE_ENCOUNTERS_H",
        "#define GUARD_CONSTANTS_CE_ENCOUNTERS_H",
        "",
        "// ce_loadenc (asm/macros/ce_encounters.inc) loads an encounter into these special vars.",
        "#define VAR_CE_ENC_SPECIES VAR_UNUSED_0x8014",
        "#define VAR_CE_ENC_LEVEL   VAR_0x800A",
        "#define VAR_CE_ENC_ITEM    VAR_0x800B",
        "",
        "// gCeEncounters[].flags",
        "enum CeEncounterFlag",
        "{",
        "    CE_ENC_FLAG_SHINY = 1 << 0,",
        "};",
        "",
        "enum CeEncounterKind",
        "{",
        *[f"    {kind_constant(k)}," for k in KINDS],
        "};",
        "",
        "enum CeEncounterId",
        "{",
        *[f"    CE_ENC_{e['id']}," for e in encounters],
        "    CE_ENC_COUNT",
        "};",
        "",
        "#endif // GUARD_CONSTANTS_CE_ENCOUNTERS_H",
        "",
    ]
    return "\n".join(lines)


def data_header(encounters: list[dict]) -> str:
    lines = [
        "// Generated by tools/ce/gen_encounters.py from ce/encounters.json. Do not edit.",
        "// Included only by src/ce/encounters_data.c.",
        "",
        "const struct CeEncounter gCeEncounters[CE_ENC_COUNT] CE_PATCHABLE =",
        "{",
    ]
    for e in encounters:
        lines.append(
            f"    [CE_ENC_{e['id']}] = {{ .species = {e['species']}, .level = {e['level']}, "
            f".flags = 0, .item = {e.get('item', 'ITEM_NONE')} }},"
        )
    lines += ["};", "", "USED const struct CeEncounterInfo gCeEncounterInfo[CE_ENC_COUNT] =", "{"]
    for e in encounters:
        trade = f", .trade = {e['trade']}" if "trade" in e else ""
        lines.append(f"    [CE_ENC_{e['id']}] = {{ .map = {e['map']}, .kind = {kind_constant(e['kind'])}{trade} }},")
    lines += ["};", ""]
    return "\n".join(lines)


def write_if_changed(path: str, text: str) -> None:
    try:
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                return
    except FileNotFoundError:
        pass
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def main() -> None:
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    src, constants_out, data_out = sys.argv[1:]
    encounters = load(src)
    write_if_changed(constants_out, constants_header(encounters))
    write_if_changed(data_out, data_header(encounters))


if __name__ == "__main__":
    main()
