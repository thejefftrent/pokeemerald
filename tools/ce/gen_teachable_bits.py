#!/usr/bin/env python3

"""
Usage: python3 tools/ce/gen_teachable_bits.py BUILD_DIR

Custom Emerald replacement for the last step of tools/learnset_helpers/make_teachables.py.

Takes the same inputs and works out the same per-species teachable moves (by calling
make_teachables itself), but writes src/data/pokemon/teachable_learnsets.h as bitsets:

    #define sBulbasaurTeachableLearnset { 0x.., ... }   // CE_TEACHABLE_BYTES bytes

so `.teachableLearnset = sBulbasaurTeachableLearnset` in species_info fills each species'
own u8[CE_TEACHABLE_BYTES] field. Bit n (byte n / 8, bit n % 8) is teachable slot n:
gTMHMItemMoveIds[n + 1] for the TMs and HMs, then gCeTutorMoves[n - NUM_ALL_MACHINES].
Species with ALL_TEACHABLES get every bit, so they can learn whatever a slot is changed to.
Also defines CE_TEACHABLE_TUTOR_MOVES, the initializer for gCeTutorMoves.
"""

import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "learnset_helpers"))
import make_teachables  # noqa: E402

OUTPUT = pathlib.Path("./src/data/pokemon/teachable_learnsets.h")
HEADER_DEFINE_PAT = re.compile(r"^#define\s+(CE_TEACHABLE_SLOTS|CE_TUTOR_SLOTS)\s+(\d+)", flags=re.MULTILINE)
LIST_PAT = re.compile(r"static const u16 s(?P<name>\w+?)TeachableLearnset\[\] = \{(?P<moves>.*?)\};\n", flags=re.DOTALL)


def read_slot_counts() -> tuple[int, int]:
    with open("./include/ce/teachable.h", "r") as fp:
        defines = dict(HEADER_DEFINE_PAT.findall(fp.read()))
    return int(defines["CE_TEACHABLE_SLOTS"]), int(defines["CE_TUTOR_SLOTS"])


def bitset_initializer(bits: set[int], num_bytes: int) -> str:
    data = [0] * num_bytes
    for bit in bits:
        data[bit // 8] |= 1 << (bit % 8)
    return "{ " + ", ".join(f"0x{b:02X}" for b in data) + " }"


def main():
    if not make_teachables.enabled():
        sys.exit("gen_teachable_bits: Custom Emerald needs P_LEARNSET_HELPER_TEACHABLE set to TRUE")
    if len(sys.argv) != 2:
        sys.exit(__doc__)

    build_dir = pathlib.Path(sys.argv[1])
    num_slots, tutor_slots = read_slot_counts()

    with open("src/data/pokemon/special_movesets.json", "r") as fp:
        special_movesets = json.load(fp)
    with open("./src/data/pokemon/all_learnables.json", "r") as fp:
        all_learnables = json.load(fp)
    with open(build_dir / "all_teaching_types.json", "r") as fp:
        teaching_types = json.load(fp)

    # Same list as make_teachables.make_move_tutors, without rewriting src/data/tutor_moves.h
    # (its own Makefile rule does that).
    with open(build_dir / "all_tutors.json", "r") as fp:
        tutors = sorted(set(json.load(fp) + special_movesets["extraTutors"]))
    machines = list(make_teachables.extract_repo_tms())  # FOREACH_TM then FOREACH_HM order
    if len(tutors) > tutor_slots:
        sys.exit(f"gen_teachable_bits: {len(tutors)} tutor moves, but only CE_TUTOR_SLOTS = {tutor_slots}")
    if len(machines) + tutor_slots > num_slots:
        sys.exit(f"gen_teachable_bits: {len(machines)} TMs/HMs + {tutor_slots} tutor slots exceed {num_slots} bits")

    slots_of: dict[str, set[int]] = {}
    for slot, move in enumerate(machines):
        slots_of.setdefault(move, set()).add(slot)
    for i, move in enumerate(tutors):
        slots_of.setdefault(move, set()).add(len(machines) + i)

    every_slot = set(range(num_slots))
    all_teachables = {
        entry["name"] for entry in teaching_types if isinstance(entry, dict) and entry["teaching_type"] == "ALL_TEACHABLES"
    }

    # make_teachables decides which moves each species gets; turn each of its lists into bits.
    lists = make_teachables.prepare_output(all_learnables, machines, tutors, special_movesets, teaching_types, "")

    def to_bits(match: re.Match) -> str:
        name = match.group("name")
        if name in all_teachables:
            bits = every_slot
        else:
            moves = [m.strip() for m in match.group("moves").split(",")]
            bits = set().union(*(slots_of.get(m, set()) for m in moves))
        return f"#define s{name}TeachableLearnset {bitset_initializer(bits, num_slots // 8)}\n"

    body, count = LIST_PAT.subn(to_bits, lists)
    if count == 0:
        sys.exit("gen_teachable_bits: make_teachables produced no learnsets")

    tutor_init = ", ".join(tutors) if tutors else "MOVE_NONE"
    content = "\n".join([
        "//",
        "// DO NOT MODIFY THIS FILE! It is auto-generated by tools/ce/gen_teachable_bits.py",
        "//",
        f"// Teachable slots: {len(machines)} TMs/HMs (gTMHMItemMoveIds order), then {len(tutors)} of {tutor_slots} tutor slots.",
        "",
        f"#define CE_TEACHABLE_GEN_MACHINES {len(machines)}",
        f"#define CE_TEACHABLE_TUTOR_MOVES {{ {tutor_init} }}",
        "",
    ]) + body.lstrip("\n")
    OUTPUT.write_text(content)


if __name__ == "__main__":
    main()
