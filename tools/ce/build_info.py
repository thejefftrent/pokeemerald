#!/usr/bin/env python3
"""Write include/ce/build_info.h, touching it only when the content changes.

CE_BASE_ID (env) names the base build, e.g. "1.17.1-ce1"; defaults to "dev".
"""
import os
import subprocess
import sys

out = sys.argv[1]
base_id = os.environ.get("CE_BASE_ID", "dev")
if len(base_id) > 23:
    sys.exit(f"CE_BASE_ID is longer than 23 characters: {base_id}")
try:
    commit = subprocess.run(["git", "rev-parse", "--short=7", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
except (OSError, subprocess.CalledProcessError):
    commit = "0"

text = (
    "// Generated by tools/ce/build_info.py. Do not edit.\n"
    f'#define CE_BASE_ID "{base_id}"\n'
    f"#define CE_FORK_COMMIT 0x{int(commit, 16):08X}\n"
)
try:
    with open(out) as f:
        if f.read() == text:
            sys.exit(0)
except FileNotFoundError:
    pass
with open(out, "w") as f:
    f.write(text)
